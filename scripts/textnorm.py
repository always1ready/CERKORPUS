"""Общие функции нормализации текста для корпуса ЖМП."""

import re
import unicodedata

# Слово — непрерывная цепочка букв (кириллица или латиница); цифры и знаки отсекаются.
WORD_RE = re.compile(r"[A-Za-zА-Яа-яЁё]+")
# Перенос на конце строки: «процве-\nтанию» → «процветанию».
# Склеиваем только если после дефиса идёт строчная буква: так не трогаем тире в начале строки.
# Между дефисом и концом строки допускаем один лишний знак: у корешка страницы
# распознавание часто ставит после переноса точку или двоеточие («са-.\nмими»).
HYPHEN_RE = re.compile(r"([A-Za-zА-Яа-яЁё])[-­][.,:;'`]?[ \t]*\n\s*([a-zа-яё])")


def dehyphenate(text: str) -> str:
    """Склеивает слова, разорванные переносом на границе строк.

    Ограничение: слова с настоящим дефисом на конце строки («церковно-\nисторический»)
    тоже склеятся. В журнале таких случаев мало, но при желании их можно
    восстанавливать по словарю.
    """
    return HYPHEN_RE.sub(r"\1\2", text)


def normalize(text: str) -> str:
    """Приводит текст к виду, в котором честно сравнивать две версии распознавания."""
    # Убираем ударения и прочие комбинируемые знаки («бо́льшую» → «большую»),
    # но сохраняем «й» и «ё» как отдельные буквы: NFC собирает их обратно.
    decomposed = unicodedata.normalize("NFD", text)
    stripped = "".join(ch for ch in decomposed if ch != "́")
    text = unicodedata.normalize("NFC", stripped)
    text = dehyphenate(text)
    text = text.lower().replace("ё", "е")
    return re.sub(r"\s+", " ", text).strip()


def words(text: str) -> list[str]:
    """Список слов нормализованного текста."""
    return WORD_RE.findall(normalize(text))
