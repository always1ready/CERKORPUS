"""Поиск церковнославянских форм в тексте гражданской печати.

Слово считаем церковнославянизмом в двух случаях:
1) оно входит в короткий список служебных и местоименных слов, которых нет
   в современном русском (яко, иже, аще, паки, мя, тя…);
2) его нет в словаре современного русского языка (pymorphy3), но после замены
   окончания на русское соответствие оно в словаре есть:
   «милостию» → «милостью», «приносити» → «приносить», «святыя» → «святой».
Второе правило отсекает опечатки распознавания и имена: у них русского
соответствия не находится.
"""

import re

import pymorphy3

MORPH = pymorphy3.MorphAnalyzer()

LEXICAL = {
    "яко", "якоже", "иже", "яже", "еже", "аще", "паки", "бо", "убо", "днесь",
    "зело", "егда", "абие", "присно", "всяк", "мя", "тя", "ти", "ны", "речет",
    "рече", "вонми", "человецех", "нощь", "нощи",
}

# Окончание церковнославянской формы → возможные русские соответствия.
ENDINGS = [
    ("тися", ["ться"]), ("ти", ["ть"]),           # инфинитив: кланятися, приносити
    ("ию", ["ью"]),                               # твор. падеж: милостию
    ("ыя", ["ой", "ые"]), ("ия", ["ей", "ие"]),   # род. ед. ж. р. прил.: святыя
    ("ея", ["ей"]),                               # твоея, моея
    ("аго", ["ого"]), ("яго", ["его"]),           # святаго, синяго
    ("ех", ["ах", "ях"]),                         # предл. мн.: скорбех, разумех
    ("юще", ["ющие"]), ("яще", ["ящие"]), ("аще", ["ащие"]),  # поюще
    ("ися", ["ился"]), ("ася", ["ался"]), ("еся", ["елся"]),  # явися, возрадовася
    ("еши", ["ешь"]), ("иши", ["ишь"]),           # терпиши
    ("ахом", ["али"]), ("ихом", ["или"]),         # уповахом
    ("аша", ["али"]), ("иша", ["или"]), ("оша", ["ли"]),       # восташа, внидоша
]
TOKEN = re.compile(r"[А-Яа-яЁё]+")


def is_slavonic(token: str) -> bool:
    word = token.lower().replace("ё", "е")
    if word in LEXICAL:
        return True
    # Слова с заглавной буквы пропускаем: среди них слишком много имён.
    if not token[0].islower() or len(word) < 5 or MORPH.word_is_known(word):
        return False
    for ending, replacements in ENDINGS:
        if word.endswith(ending):
            stem = word[: -len(ending)]
            return any(MORPH.word_is_known(stem + r) for r in replacements)
    return False


def find(text: str) -> list[str]:
    """Церковнославянские формы в тексте, в нижнем регистре."""
    return [t.lower() for t in TOKEN.findall(text) if is_slavonic(t)]
